import type { Achievement, Player } from "../types";

/**
 * Basketball roster — 32 of the consensus all-time greats, every honor count
 * verified against English Wikipedia infoboxes (cutoff: end of the 2024-25 NBA
 * season, June 2025; post-cutoff 2025-26 figures Wikipedia already shows were
 * excluded). Counts are exact. For the marquee honors the YEARS are the exact
 * award years; for the high-volume secondary selections (All-NBA 2nd/3rd,
 * All-Defensive, stat titles) where only the count is load-bearing, years are
 * either the exact list (when documented) or spread across the verified span —
 * the Honor Index score depends only on the count, never the year.
 */

// Exact-year honors.
const A = (type: string, years: number[]): Achievement[] => years.map((year) => ({ type, year }));
// Count-only honors: distribute `count` entries across [first, last] for display.
const spread = (type: string, count: number, first: number, last: number): Achievement[] => {
  if (count <= 0) return [];
  if (count === 1) return [{ type, year: first }];
  const step = (last - first) / (count - 1);
  return Array.from({ length: count }, (_, i) => ({ type, year: Math.round(first + step * i) }));
};

